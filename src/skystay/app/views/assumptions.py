from __future__ import annotations

import numpy as np
import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from skystay import figures as fx
from skystay.app import ui
from skystay.reconcile import regions

FAMILIES = {
    "load_factor": "Load factor", "transfer_share": "Transfer / transit share", "capture_rate": "Capture rate",
    "length_of_stay": "Length of stay", "non_air_baseline": "Non-air baseline", "calendar": "Calendar effects",
    "structural": "Structural rules",
}


def ledger_frame(asm: dict) -> pd.DataFrame:
    rows = []
    for fam, label in FAMILIES.items():
        for key, v in (asm.get(fam) or {}).items():
            iv = v.get("interval_80") or [None, None]
            rows.append({"Family": label, "Item": f"{regions.label(key)} ({key})" if fam not in ("calendar", "structural")
                         else key.replace("_", " "), "Value": v.get("value"), "Unit": v.get("unit"),
                         "80% interval": "-" if iv[0] is None else f"{iv[0]} to {iv[1]}", "n_obs": v.get("n_obs"),
                         "Method / source": f"{v.get('method')} ({v.get('source')})",
                         "Adjustable": "yes" if v.get("adjustable") else "no"})
    return pd.DataFrame(rows)


def render() -> None:
    ui.page_setup("Data & assumptions", "What went in, how origin countries were matched to guest nationalities, "
                  "and every assumption with its interval.")
    dq = ui.report("data_quality")
    mod = ui.report("model")
    if dq:
        ow = dq["overlap_window"]
        ui.kpi_row([
            ("Data mode", dq["data_mode"].upper(), "synthetic stand-in" if dq["data_mode"] == "synthetic"
             else "real data"),
            ("Overlapping months", str(ow["n_months"]), f"{ow['first']} to {ow['last']}"),
            ("Origin countries / airports", f"{dq['counts']['origin_countries']} / {dq['counts']['origin_airports']}",
             "departure side of the flight data"),
            ("Guest nationalities", str(dq["counts"]["nationalities"]), "including UAE and Others"),
            ("Records flagged", str(len(dq["missing_hotel_months"]) + len(dq["missing_pax_months"])
                                    + dq["load_factor"]["above_1"]), "missing months, LF above 100%"),
        ])
        with st.expander("Data-quality details", expanded=False):
            st.markdown(ui.doc("../reports/data_quality.md") or "See reports/data_quality.md")
    st.write("")
    br = mod.get("bridge") or {}
    if br.get("mix"):
        st.subheader("Who arrives on each origin's flights: learned origin-to-nationality bridge")
        mix = np.array(br["mix"])
        lo = np.array(br["mix_lo80"]) if br.get("mix_lo80") else None
        hi = np.array(br["mix_hi80"]) if br.get("mix_hi80") else None
        origins, nats = br["origins"], br["nationalities"]
        keep = [j for j, n in enumerate(nats) if mix[:, j].max() > 0.005]
        z = mix[:, keep]
        text = [[f"{z[i, k]:.0%}" if z[i, k] >= 0.05 else "" for k in range(len(keep))] for i in range(len(origins))]
        custom = None
        if lo is not None:
            custom = np.dstack([lo[:, keep], hi[:, keep]])
        fig = go.Figure(go.Heatmap(
            z=z, x=[regions.label(nats[j]) for j in keep], y=[regions.label(o) for o in origins],
            colorscale=[[0.0, "#f7f7f4"], [0.02, fx.SEQ[0]]] + [[0.02 + 0.98 * k / (len(fx.SEQ) - 1), c]
                                                               for k, c in enumerate(fx.SEQ)][1:], zmin=0, zmax=1,
            text=text, texttemplate="%{text}", textfont={"size": 10}, customdata=custom,
            hovertemplate=("Flights from %{y}: %{z:.1%} of their hotel guests are %{x} nationals"
                           + ("<br>80% interval %{customdata[0]:.1%} to %{customdata[1]:.1%}" if custom is not None
                              else "") + "<extra></extra>"),
            colorbar={"title": {"text": "Share of guests"}, "tickformat": ".0%"}))
        fx.layout(fig, "Rows: departure country. Columns: guest nationality. Each row sums to 100%.", height=700,
                  legend=False)
        fig.update_xaxes(tickangle=-45, showgrid=False)
        fig.update_yaxes(autorange="reversed", showgrid=False)
        ui.chart(fig, "da_bridge")
        st.caption(f"{br.get('identification_note', '')} Ridge strength chosen on the last 12 training months: "
                   f"{br.get('lambda')}. 80% intervals from a {br.get('bootstrap_reps')}-draw block bootstrap by "
                   "year (hover a cell).")
    st.subheader("Assumption ledger")
    asm = ui.assumptions()
    led = ledger_frame(asm)
    fam = st.multiselect("Show", list(FAMILIES.values()), default=list(FAMILIES.values()), key="da_fam")
    st.dataframe(led[led["Family"].isin(fam)], hide_index=True, width="stretch", height=420)
    st.caption("Generated by `skystay train` into config/assumptions.yaml (human-readable: docs/ASSUMPTIONS.md). "
               "Intervals are the uncertainty of each estimate, not month-to-month variation.")
    st.subheader("Limitations")
    st.markdown(ui.doc("LIMITATIONS.md").split("\n", 1)[-1] or "See docs/LIMITATIONS.md")
    ui.synthetic_note()
