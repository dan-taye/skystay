"""`skystay data`: generate (synthetic mode) or locate raw files, ingest, check, store."""

from __future__ import annotations

import pandas as pd

from skystay import paths, settings
from skystay.io import adapters, quality, store, synthetic


def source_folder() -> tuple[str, object]:
    mode = settings.write_settings()["data_mode"]
    if mode == "synthetic":
        print("DATA_MODE=synthetic: generating stand-in data (seed 42)")
        synthetic.generate()
        return mode, paths.SYNTH_GEN
    print(f"DATA_MODE=real: ingesting {len(settings.raw_files())} file(s) from data/raw/")
    return mode, paths.RAW


def run() -> dict:
    paths.ensure_dirs()
    mode, folder = source_folder()
    tables, logs = adapters.ingest(folder)
    am, am_stats = quality.derive_airport_month(tables["flights_month"], tables["pax_month"])
    tr = am[["month", "origin_airport", "transfer_share"]]
    fm = tables["flights_month"].drop(columns="transfer_share").merge(tr, on=["month", "origin_airport"], how="left")
    tables["flights_month"] = fm[
        ["month", "origin_airport", "origin_country", "airline", "aircraft_type", "flights", "seats",
         "weekly_freq_avg", "transfer_share"]
    ]
    tables["airport_month"] = am
    rep = quality.report(tables, logs, am_stats)
    store.write_tables(tables)
    write_data_notes(tables, rep)
    ow = rep["overlap_window"]
    print(f"stored {len(tables)} tables in {paths.DB_PATH.relative_to(paths.ROOT)}; "
          f"overlap window {ow['first']}..{ow['last']} ({ow['n_months']} months)")
    return rep


def write_data_notes(tables: dict[str, pd.DataFrame], rep: dict) -> None:
    syn = rep["data_mode"] == "synthetic"
    cov = rep["coverage"]
    c = rep["counts"]
    lines = [
        "# Data notes",
        "",
        "_Generated by `skystay data` from the ingested tables; coverage figures are computed, caveats are maintained in "
        "`src/skystay/io/pipeline.py`._",
        "",
    ]
    if syn:
        lines += [
            "> **SYNTHETIC DEMO DATA.** No real data is in `data/raw/`, so these tables come from the "
            "seeded generator in `src/skystay/io/synthetic.py` (config `data/synthetic/generator.yaml`). Its layout "
            "mimics the aggregated data a tourism planner would have (flight schedule, passenger traffic, hotel performance, calendars); its numbers say nothing about Abu Dhabi.",
            "",
        ]
    lines += [
        "## Datasets",
        "",
        "| Canonical table | Grain | Units | Coverage | Caveats |",
        "| :- | :- | :- | :- | :- |",
        f"| flights_month | route (origin airport x airline x aircraft type) x month, aggregated from a daily schedule | "
        f"flights, seats; weekly_freq_avg = flights / days x 7 | {cov['flights_month']['first']}..{cov['flights_month']['last']} | "
        f"`origin_country` is the DEPARTURE country, not passenger nationality. {c['origin_countries']} countries, "
        f"{c['origin_airports']} airports. |",
        f"| pax_month | origin airport x month | arriving passengers; transfer passengers | {cov['pax_month']['first']}.."
        f"{cov['pax_month']['last']} | Transfer/transit share = transfer / arriving (the connection indicator). "
        f"Returning residents are not observable in aggregated traffic. |",
        f"| hotel_month | guest nationality x month | guest arrivals, guest nights, ALOS (nights), occupancy (%) | "
        f"{cov['hotel_month']['first']}..{cov['hotel_month']['last']} | `nationality` is GUEST NATIONALITY. Includes UAE "
        f"(domestic) and an 'Others' bucket. {c['nationalities']} nationalities. Occupancy is an all-hotel monthly value. |",
        f"| events | event | start/end dates | {c['events']} events | Abu Dhabi event calendar"
        f"{' (generic placeholder names)' if syn else ''}. |",
        f"| holidays | country x date | holiday days | {c['holiday_days']:,} rows | Source-market holidays"
        f"{' (approximate dates)' if syn else ''}. |",
        "| seasonality | month of year | index (mean 1) | 12 rows | Used as the shape of the non-air baseline. |",
        "| market_map | country | ISO 3166 alpha-2 + region | from config/regions.yaml | Single source of truth for keys. |",
        "| airport_month (derived) | origin airport x month | seats, pax, load factor, transfer share | as above | "
        "LF > 1.0 flagged; clipped at 1.05. |",
        "",
        "## The country catch",
        "",
        "Flight data says where a plane departed; hotel data says what passport the guest holds. Hubs (e.g. London, "
        "Singapore) carry many nationalities, expatriate residents fly from their country of residence, residents return "
        "home, and some guests arrive by land or via other UAE airports. We therefore never assume the two keys are the "
        "same; we compare three reconciliation levels (identity, regional, learned bridge) in the back-test.",
        "",
        "## Modelling window",
        "",
        f"Overlap of flights, traffic and hotel data: {rep['overlap_window']['first']} to {rep['overlap_window']['last']} "
        f"({rep['overlap_window']['n_months']} months). {rep['reconciliation_feasibility']['note']}.",
        "",
        "See `reports/data_quality.md` for missing records, duplicates, outliers and load-factor flags.",
        "",
    ]
    paths.DOCS.mkdir(parents=True, exist_ok=True)
    (paths.DOCS / "DATA_NOTES.md").write_text("\n".join(lines), encoding="utf-8")
