"""Settings, team info and data-mode detection."""

from __future__ import annotations

from functools import lru_cache
from typing import Any

import yaml

from skystay import paths

TBC = "[TEAM TO CONFIRM]"

DEFAULT_SETTINGS: dict[str, Any] = {
    "data_mode": "synthetic",
    "seed": 42,
    "backtest": {"horizon_months": 12, "n_folds": 3, "holdout_months": 12},
    "reconciliation": {"min_months_for_bridge": 36, "hub_origins": ["GB", "DE", "SG", "US", "QA"]},
    "scenario": {"draws": 500, "reference_months": 12},
    "seasons": {
        "Winter peak (Dec-Feb)": [12, 1, 2],
        "Spring (Mar-May)": [3, 4, 5],
        "Summer low (Jun-Aug)": [6, 7, 8],
        "Autumn (Sep-Nov)": [9, 10, 11],
    },
}


def raw_files() -> list[str]:
    if not paths.RAW.exists():
        return []
    return sorted(
        p.name for p in paths.RAW.iterdir() if p.is_file() and not p.name.startswith(".")
    )


def detect_data_mode() -> str:
    return "real" if raw_files() else "synthetic"


def write_settings() -> dict[str, Any]:
    """Detect the data mode and (re)write config/settings.yaml, keeping user edits."""
    current = DEFAULT_SETTINGS.copy()
    if paths.SETTINGS_FILE.exists():
        loaded = yaml.safe_load(paths.SETTINGS_FILE.read_text(encoding="utf-8")) or {}
        current.update(loaded)
    current["data_mode"] = detect_data_mode()
    paths.CONFIG.mkdir(parents=True, exist_ok=True)
    header = (
        "# Generated by `skystay setup`. data_mode is detected: real if data/raw/ has files,\n"
        "# otherwise synthetic. Other keys may be edited by hand.\n"
    )
    paths.SETTINGS_FILE.write_text(
        header + yaml.safe_dump(current, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )
    load_settings.cache_clear()
    return current


@lru_cache(maxsize=1)
def load_settings() -> dict[str, Any]:
    if not paths.SETTINGS_FILE.exists():
        return write_settings()
    data = yaml.safe_load(paths.SETTINGS_FILE.read_text(encoding="utf-8")) or {}
    merged = DEFAULT_SETTINGS.copy()
    merged.update(data)
    return merged


def data_mode() -> str:
    return str(load_settings()["data_mode"])


def is_synthetic() -> bool:
    return data_mode() == "synthetic"


def seasons() -> dict[str, list[int]]:
    return dict(load_settings()["seasons"])


def season_of_month(month_of_year: int) -> str:
    for name, months in seasons().items():
        if month_of_year in months:
            return name
    raise ValueError(f"month {month_of_year} not in any season")


@lru_cache(maxsize=1)
def load_team() -> dict[str, Any]:
    if not paths.TEAM_FILE.exists():
        return {"team_name": "", "members": [], "product_name": "SkyStay"}
    return yaml.safe_load(paths.TEAM_FILE.read_text(encoding="utf-8")) or {}


def product_name() -> str:
    return str(load_team().get("product_name") or "SkyStay").strip()


def team_name() -> str:
    return str(load_team().get("team_name") or "").strip() or TBC


def team_members() -> list[dict[str, str]]:
    out = []
    for m in load_team().get("members") or []:
        out.append(
            {
                "name": (m.get("name") or "").strip() or TBC,
                "role": (m.get("role") or "").strip() or TBC,
            }
        )
    return out


def is_personal() -> bool:
    return str(load_team().get("project_type", "team")).strip().lower() == "personal"


def author() -> str:
    return str(load_team().get("author") or "").strip() or TBC


def byline() -> str:
    """'A personal project by <author>' or 'Team: <name>'."""
    return f"A personal project by {author()}" if is_personal() else f"Team: {team_name()}"
